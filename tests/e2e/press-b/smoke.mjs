import { launch, context, login, api, assert, shot, summary } from './lib.mjs';
const browser = await launch();
const ctx = await context(browser);
const page = await ctx.newPage();
await login(page);
const r = await api(page, 'GET', '/api/decks');
assert(r.status === 200, 'api list decks ' + r.status + ' ' + r.text.slice(0, 200));
await shot(page, 'smoke-library');
const id = r.json.data[0].id;
await page.goto('/decks/' + id);
await page.waitForTimeout(2500);
await shot(page, 'smoke-editor');
console.log(ctx._errors);
summary('smoke');
await browser.close();
